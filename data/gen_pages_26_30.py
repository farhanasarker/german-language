# Separate into B, C, D entries
def get_letter(word):
    w = word.strip()
    if w.startswith("sich "):
        w = w[5:]
    if w.startswith("ein "):
        w = w[4:]
    first = w[0].upper()
    return first

def write_csv(filename, entries):
    filepath = os.path.join(CSV_DIR, filename)
    # Read existing entries if file exists
    existing = []
    if os.path.exists(filepath):
        with open(filepath, 'r', encoding='utf-8') as f:
            reader = csv.reader(f)
            header = next(reader)  # skip header
            for row in reader:
                existing.append(row)

    # Append new entries (avoid duplicates by word)
    existing_words = {row[0] for row in existing}
    new_entries = []
    for e in entries:
        if e[0] not in existing_words:
            new_entries.append(e)

    with open(filepath, 'w', encoding='utf-8', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(["Word", "Article", "Plural", "WordType", "English", "Bangla",
                          "Partizip_II", "Auxiliary", "Example_Sentence", "Synonyms", "Antonyms"])
        for row in existing:
            writer.writerow(row)
        for row in new_entries:
            writer.writerow(row)

    return len(new_entries), len(existing)

# Group entries by first letter
groups = {}
for entry in ENTRIES:
    letter = get_letter(entry[0])
    groups.setdefault(letter, []).append(entry)

for letter, entries in sorted(groups.items()):
    filename = f"{letter}.csv"
    new_count, existing_count = write_csv(filename, entries)
    print(f"{filename}: {existing_count} existing, {new_count} new entries added")
